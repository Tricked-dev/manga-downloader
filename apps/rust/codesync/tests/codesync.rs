#[test]
fn sync_replays_source_head_into_destination() -> Result<()> {
    if !git_available() {
        return Ok(());
    }

    let temp = TempDir::new()?;
    let source = temp.path().join("source");
    let destination_bare = temp.path().join("destination.git");
    let destination_seed = temp.path().join("destination-seed");
    let destination_check = temp.path().join("destination-check");
    let config_path = temp.path().join("codesync.star");

    git(temp.path(), ["init", "--initial-branch=main", "source"])?;
    fs::create_dir_all(source.join("src"))?;
    fs::write(
        source.join("src/lib.rs"),
        "pub const NAME: &str = \"internal\";\n",
    )?;
    git(&source, ["add", "."])?;
    git(
        &source,
        [
            "-c",
            "user.name=Source Author",
            "-c",
            "user.email=source@example.com",
            "commit",
            "-m",
            "Add source library",
        ],
    )?;

    git(temp.path(), ["init", "--bare", "destination.git"])?;
    git(
        temp.path(),
        [
            "clone",
            destination_bare
                .to_str()
                .context("destination path was not utf-8")?,
            destination_seed
                .to_str()
                .context("seed path was not utf-8")?,
        ],
    )?;
    fs::write(destination_seed.join("README.md"), "public repo\n")?;
    git(&destination_seed, ["add", "."])?;
    git(
        &destination_seed,
        [
            "-c",
            "user.name=Public Author",
            "-c",
            "user.email=public@example.com",
            "commit",
            "-m",
            "Initial public repo",
        ],
    )?;
    git(
        &destination_seed,
        ["push", "origin", "HEAD:refs/heads/main"],
    )?;

    fs::write(
        &config_path,
        format!(
            r#"
workflow(
    name = "demo",
    origin = git_origin(url = "{}", ref = "main"),
    destination = git_destination(url = "{}", ref = "main"),
    destination_files = glob(["third_party/demo/**"]),
    transformations = [
        replace(before = "internal", after = "public", paths = glob(["**/*.rs"])),
        move("", "third_party/demo"),
    ],
)
"#,
            source.display(),
            destination_bare.display()
        ),
    )?;

    let config = codesync::load_config(&config_path)?;
    let plans = plan_workflows(&config, &PlanOptions::default())?;
    assert_eq!(plans.len(), 1);
    assert_eq!(plans[0].commits.len(), 1);

    let reports = sync_workflows(
        &config,
        &SyncOptions {
            push: true,
            ..SyncOptions::default()
        },
    )?;
    assert_eq!(reports[0].committed, 1);

    git(
        temp.path(),
        [
            "clone",
            destination_bare
                .to_str()
                .context("destination path was not utf-8")?,
            destination_check
                .to_str()
                .context("check path was not utf-8")?,
        ],
    )?;
    git(&destination_check, ["checkout", "main"])?;

    let synced = fs::read_to_string(destination_check.join("third_party/demo/src/lib.rs"))?;
    assert!(synced.contains("\"public\""));

    let log = git(&destination_check, ["log", "-1", "--format=%B"])?;
    assert!(log.contains("CodeSync-Workflow: demo"));
    assert!(log.contains("CodeSync-Source-Rev:"));

    Ok(())
}

