#[test]
fn starlark_config_declares_workflow() -> Result<()> {
    let config = load_config_from_str(
        "test.star",
        r#"
workflow(
    name = "demo",
    origin = git_origin(url = "internal", ref = "main"),
    destination = git_destination(url = "public", ref = "main"),
    destination_files = glob(["third_party/demo/**"], exclude = ["third_party/demo/README.md"]),
    transformations = [
        replace(before = "internal", after = "public", paths = glob(["**/*.rs"])),
        move("", "third_party/demo"),
    ],
)
"#,
    )?;

    assert_eq!(config.workflows.len(), 1);
    let workflow = &config.workflows[0];
    assert_eq!(workflow.name, "demo");
    assert_eq!(workflow.origin.reference, "main");
    assert_eq!(workflow.destination.reference, "main");
    assert_eq!(workflow.transformations.len(), 2);
    assert!(matches!(
        workflow.transformations[0],
        Transformation::Replace { .. }
    ));

    Ok(())
}

#[test]
fn copybara_style_config_declares_workflow() -> Result<()> {
    let config = load_config_from_str(
        "copy.bara.sky",
        r#"
service.migration(None)
service.notifications({})

core.workflow(
    name = "demo",
    origin = git.origin(url = "internal", fetch = "main"),
    destination = git.github_destination(
        url = "public",
        fetch = "main",
        push = "codesync/demo",
        pr_branch = "codesync/demo",
        title = "Sync demo",
        body = "Generated by codesync.",
    ),
    origin_files = glob(["src/**"]),
    destination_files = glob(["third_party/demo/**"]),
    authoring = authoring.pass_thru(),
    mode = "ITERATIVE",
    transformations = [
        core.replace(before = "internal", after = "public", paths = glob(["**/*.rs"])),
        core.move("", "third_party/demo"),
    ],
)
"#,
    )?;

    assert_eq!(config.workflows.len(), 1);
    let workflow = &config.workflows[0];
    assert_eq!(workflow.origin.reference, "main");
    assert_eq!(workflow.destination.reference, "main");
    assert_eq!(
        workflow.destination.push_reference.as_deref(),
        Some("codesync/demo")
    );
    assert_eq!(
        workflow
            .destination
            .pull_request
            .as_ref()
            .and_then(|pr| pr.branch.as_deref()),
        Some("codesync/demo")
    );
    assert_eq!(
        workflow.origin_files.as_ref().map(|files| &files.include),
        Some(&vec!["src/**".to_owned()])
    );

    Ok(())
}

